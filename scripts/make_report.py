"""Build results/RESULTS.md from the saved JSON files, so every number in the
README traces back to a file produced by a real run (no hand-typed metrics)."""
import glob
import json
import os
import statistics

R = "results"


def load(path):
    with open(path) as f:
        return json.load(f)


def fmt_ci(d):
    return f"{d['mean']:.3f} [{d['ci95'][0]:.3f}, {d['ci95'][1]:.3f}]"


def run_row(name):
    p = f"{R}/{name}/summary.json"
    if not os.path.exists(p):
        return None
    s = load(p)
    sl = s["slices_exact_match"]
    return (f"| {name} | {s['n']} | {fmt_ci(s['exact_match'])} | {fmt_ci(s['field_score'])} | "
            + " | ".join(f"{sl[k]['mean']:.2f}" for k in ("clean", "encoding", "missing_field", "renamed_field"))
            + f" | {s['valid_json_rate']:.3f} |")


def seed_mean(names):
    vals = [load(f"{R}/{n}/summary.json")["exact_match"]["mean"] for n in names
            if os.path.exists(f"{R}/{n}/summary.json")]
    if not vals:
        return None
    sd = statistics.stdev(vals) if len(vals) > 1 else 0.0
    return f"{statistics.mean(vals):.3f} (sd {sd:.3f}, {len(vals)} seeds: " + ", ".join(f"{v:.3f}" for v in vals) + ")"


def cmp_row(path):
    c = load(path)
    o = c["overall"]["exact"]
    return (f"| {os.path.basename(path).replace('.json', '')} | {o['mean_diff']:+.3f} "
            f"[{o['ci_low']:+.3f}, {o['ci_high']:+.3f}] | {o['ci_excludes_zero']} |")


def main():
    lines = ["# Results (auto-generated by scripts/make_report.py)", "",
             "All data is synthetic. Exact match = all 6 fields correct. Brackets = 95% bootstrap CI.",
             "Slice columns = exact match per noise slice.", ""]
    header = ("| run | n | exact match | field score | clean | encoding | missing | renamed | valid JSON |\n"
              "|---|---|---|---|---|---|---|---|---|")
    for title, names in [
        ("In-distribution test split (new seeds, training formats)",
         ["baseline"] + [f"sft_seed{i}" for i in range(3)] + [f"grpo_base_seed{i}" for i in range(3)]
         + ["grpo_base_penalty_seed0"]),
        ("Held-out-format split (test_ood: templates, labels, date/amount formats unseen in training)",
         ["baseline_ood"] + [f"sft_seed{i}_ood" for i in range(3)]),
        ("Validation split (used only for error analysis / choosing the RL focus)", ["sft_seed0_val"]),
    ]:
        rows = [r for r in (run_row(n) for n in names) if r]
        if rows:
            lines += [f"## {title}", "", header, *rows, ""]

    lines += ["## Across training seeds (exact match)", ""]
    for label, names in [("SFT, test", [f"sft_seed{i}" for i in range(3)]),
                         ("SFT, test_ood", [f"sft_seed{i}_ood" for i in range(3)]),
                         ("GRPO from base, test", [f"grpo_base_seed{i}" for i in range(3)])]:
        m = seed_mean(names)
        if m:
            lines.append(f"- {label}: {m}")
    lines.append("")

    comps = sorted(p for p in glob.glob(f"{R}/comparisons/*.json") if "identity" not in p)
    if comps:
        lines += ["## Paired comparisons (B minus A, exact match, same items)", "",
                  "| comparison | mean diff [95% CI] | CI excludes 0 |", "|---|---|---|",
                  *[cmp_row(p) for p in comps], ""]

    g = f"{R}/grpo_from_sft_seed0/train_meta.json"
    if os.path.exists(g):
        logs = [h for h in load(g)["log_history"] if "frac_reward_zero_std" in h]
        lines += ["## GRPO starting from the SFT model (learning-signal check)", "",
                  "| step | mean reward | frac. groups with zero reward std |", "|---|---|---|",
                  *[f"| {h['step']} | {float(h['reward']):.3f} | {float(h['frac_reward_zero_std']):.2f} |" for h in logs], ""]

    inf = sorted(p for p in glob.glob(f"{R}/inference/*.json") if not p.endswith("model_sizes.json"))
    sizes_p = f"{R}/inference/model_sizes.json"
    sizes = load(sizes_p) if os.path.exists(sizes_p) else {}
    if inf:
        lines += ["## Inference benchmark", "",
                  "| run | quant | exact match | latency b=1 median (s) | req/s b=1 | req/s b=4 | req/s b=16 | serialized model MB | peak RSS MB |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for p in inf:
            b = load(p)
            t = b["throughput"]
            lines.append(f"| {b['name']} | {b['quant']} | {fmt_ci(b['quality']['exact_match'])} | "
                         f"{b['latency_batch1_s']['median']:.2f} | "
                         + " | ".join(f"{t[k]['requests_per_s']:.2f}" if k in t else "-" for k in ("1", "4", "16"))
                         + f" | {sizes.get(b['name'], {}).get('serialized_state_dict_bytes', b['memory']['model_bytes']) / 1e6:.0f}"
                         f" | {b['memory']['peak_rss_bytes'] / 1e6:.0f} |")
        lines.append("")

    with open(f"{R}/RESULTS.md", "w") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
